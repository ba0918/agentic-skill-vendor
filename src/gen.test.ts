const COPY = "skills/review-writer/references/vendor/verdict-format.md";
const MANIFEST = "vendor-manifest.json";

// deno-lint-ignore no-explicit-any
type Json = any;

async function readManifest(root: string): Promise<Json> {
  return JSON.parse(await fs.readFile(`${root}/${MANIFEST}`, "utf8"));
}

async function writeManifest(root: string, manifest: Json): Promise<void> {
  await fs.writeFile(
    `${root}/${MANIFEST}`,
    JSON.stringify(manifest, null, 2) + "\n",
  );
}

function kindsOf(lines: string[]): string[] {
  return lines.map((line) => line.slice(0, line.indexOf(":")));
}

test("gen leaves an already generated tree byte identical", async () => {
  await withGoodTree(async (root) => {
    const before = await snapshotTree(root);
    const result = await runCli(["gen", "--root", root]);
    expect(result.code, result.stderr.join("\n")).toStrictEqual(0);
    expect(await snapshotTree(root)).toStrictEqual(before);
  });
});

test("generating twice from the same input is byte identical", async () => {
  await withGoodTree(async (root) => {
    await fs.rm(`${root}/${COPY}`);
    expect((await runCli(["gen", "--root", root])).code).toStrictEqual(0);
    const first = await snapshotTree(root);
    expect((await runCli(["gen", "--root", root])).code).toStrictEqual(0);
    expect(await snapshotTree(root)).toStrictEqual(first);
  });
});

test("a vendored copy carries the do-not-edit header, its id and its source digest", async () => {
  await withGoodTree(async (root) => {
    await fs.rm(`${root}/${COPY}`);
    expect((await runCli(["gen", "--root", root])).code).toStrictEqual(0);
    const written = await fs.readFile(`${root}/${COPY}`, "utf8");
    const digest = (await readManifest(root)).lock.resolutions["verdict-format"]
      .digest;
    expect(written.split("\n").slice(0, 4)).toStrictEqual([
      "<!-- DO NOT EDIT. Generated by agentic-skill-vendor. -->",
      "<!-- contract: verdict-format -->",
      `<!-- source-digest: ${digest} -->`,
      "",
    ]);
  });
});

