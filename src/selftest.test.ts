import { assertEquals, assertStringIncludes } from "@std/assert";
import { copy } from "@std/fs";
import type { Sink } from "./errors.ts";
import { runCli, snapshotTree, withEmptyDir, withGoodTree } from "./testing.ts";

const SOURCE_DIR = new URL(".", import.meta.url).pathname;
const ENTRY = "cli.ts";

/**
 * Loads a copy of the tool with one edit applied to one of its modules,
 * standing in for the tool having been altered between the version a consumer
 * reviewed and the run. The whole source directory is copied, because a module
 * that no longer sits beside the ones it imports would fail to load for a
 * reason that has nothing to do with what the edit changed.
 */
async function runAltered(
  dir: string,
  file: string,
  find: string,
  replaceWith: string,
): Promise<{ code: number; stdout: string[] }> {
  const tool = `${dir}/tool`;
  await copy(SOURCE_DIR, tool);
  const path = `${tool}/${file}`;
  const source = await Deno.readTextFile(path);
  assertStringIncludes(source, find);
  await Deno.writeTextFile(path, source.replace(find, replaceWith));

  const module = await import(`file://${tool}/${ENTRY}`) as {
    run: (argv: string[], out: Sink, err: Sink) => Promise<number>;
  };
  const stdout: string[] = [];
  const code = await module.run(["self-test"], (l) => stdout.push(l), () => {});
  return { code, stdout };
}

Deno.test("self-test passes against the vectors the tool carries", async () => {
  const result = await runCli(["self-test"]);
  assertEquals(result.stdout, []);
  assertEquals(result.code, 0);
});

Deno.test("self-test reads no file, so it runs against a root that does not exist", async () => {
  const result = await runCli(["self-test", "--root", "/no/such/tree"]);
  assertEquals(result.code, 0);
});

Deno.test("self-test leaves the tree it is pointed at untouched", async () => {
  await withGoodTree(async (root) => {
    const before = await snapshotTree(root);
    assertEquals((await runCli(["self-test", "--root", root])).code, 0);
    assertEquals(await snapshotTree(root), before);
  });
});

Deno.test("self-test fails when the digest it computes stops matching its vector", async () => {
  await withEmptyDir(async (dir) => {
    // Stops the blank lines after the frontmatter from being absorbed into
    // the separator, which changes what every contract digests to.
    const result = await runAltered(
      dir,
      "digest.ts",
      'while (start < lines.length && lines[start] === "") start++;',
      'while (start < lines.length && lines[start] === "\\u0000") start++;',
    );
    assertEquals(result.code, 1);
    assertEquals(result.stdout.length > 0, true);
    assertStringIncludes(result.stdout.join("\n"), "self-test:");
  });
});

Deno.test("self-test fails when the vendored copy header stops matching its vector", async () => {
  await withEmptyDir(async (dir) => {
    const result = await runAltered(
      dir,
      "gen.ts",
      "<!-- DO NOT EDIT. Generated by ${GENERATOR.name}. -->",
      "<!-- DO NOT EDIT. Made by ${GENERATOR.name}. -->",
    );
    assertEquals(result.code, 1);
    assertStringIncludes(result.stdout.join("\n"), "self-test:");
  });
});

Deno.test("self-test fails when the conformance framing stops matching its vector", async () => {
  await withEmptyDir(async (dir) => {
    const result = await runAltered(
      dir,
      "conformance.ts",
      "encoder.encode(`${entry.path}\\0${entry.content.length}\\0`)",
      "encoder.encode(`${entry.path}\\0${entry.content.length}\\0\\0`)",
    );
    assertEquals(result.code, 1);
    assertStringIncludes(result.stdout.join("\n"), "self-test:");
  });
});
